package main

// The three templates.
//
// They are deliberately plain data: no dependency on bash-completion beyond the
// fact that bash looks the file up by name, no compinit magic beyond what every
// zsh has, and no call back into sl while the user is typing -- that would put a
// process start on every TAB.

import (
	"fmt"
	"strings"
)

// pathValued are the options whose value is a path: for those the shell's own
// file completion is the right answer, so the scripts stay out of the way.
var pathValued = map[string]bool{
	"config": true, "startup": true, "mounts": true,
}

// commandValued are the options that run a shell command: the shell can offer
// command names for those.
var commandValued = map[string]bool{
	"annotate": true, "annotate-batch": true,
}

// bash emits a bash-completion script.
func bash(opts []opt) string {
	_, valued, _, fixed := classify(opts)
	var b strings.Builder
	b.WriteString(`# bash completion for sl -- generated by tools/completions, do not edit
#
# Install: /usr/share/bash-completion/completions/sl (loaded automatically),
# or:      source completions/sl.bash

_sl() {
    local cur prev name
    COMPREPLY=()
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"

    # --option=value: values attached with an equals sign
    if [[ $cur == --*=* ]]; then
        name="${cur%%=*}"
        name="${name#--}"
        case $name in
`)
	for _, long := range sortedKeys(fixed) {
		if long == "rule" {
			continue
		}
		fmt.Fprintf(&b, "        %s) COMPREPLY=( $(compgen -W %q -- \"${cur#*=}\") ); return ;;\n",
			long, strings.Join(fixed[long], " "))
	}
	b.WriteString(`        esac
        return
    fi

    # the value of the previous option
    case $prev in` + "\n")
	for _, long := range valued {
		// --rule is handled below, after the case statement
		if long == "rule" {
			continue
		}
		if v, ok := fixed[long]; ok {
			fmt.Fprintf(&b, "        --%s) COMPREPLY=( $(compgen -W %q -- \"$cur\") ); return ;;\n",
				long, strings.Join(v, " "))
			continue
		}
		what := "a value"
		if pathValued[long] {
			what = "a path"
		}
		fmt.Fprintf(&b, "        --%s) return ;;   # %s: bash completes it\n", long, what)
	}
	b.WriteString(`    esac

    # --rule takes "RE -> GROUP"; once a --rule is on the line, the words after
    # it belong to the rule, and after the arrow only a group name makes sense
    local i
    for (( i=1; i < COMP_CWORD; i++ )); do
        if [[ ${COMP_WORDS[i]} == --rule ]]; then
            # A rule is "RE -> GROUP" and may be typed as one word or as
            # several. Three cases, and the arrow decides which one:
            #   --rule RE -> |TAB        arrow is a word of its own: a bare group
            #   --rule RE -> im|TAB      same, with a prefix
            #   --rule 'RE -> im'|TAB    arrow inside the word: keep the prefix
            # Candidates contain a space, so they are filtered by hand:
            # compgen -W splits its word list on IFS.
            local head="" bare=0
            if [[ $prev == '->' ]]; then
                bare=1
            elif [[ $cur == *'->'* && $cur != '->'* ]]; then
                head="${cur%->*}"
            elif [[ $prev == *'->' ]]; then
                head="${prev%->*}"
            else
                return
            fi
            local g cand
            for g in ` + strings.Join(groups, " ") + `; do
                if (( bare )); then
                    [[ $g == "$cur"* ]] && COMPREPLY+=( "$g" )
                    continue
                fi
                cand="${head}-> ${g}"
                [[ $cand == "$cur"* ]] && COMPREPLY+=( "$cand" )
            done
            return
        fi
    done

    case $cur in
        --*)
            COMPREPLY=( $(compgen -W "` + prefixAll(longs(opts), "--") + `" -- "$cur") )
            return ;;
        -*)
            COMPREPLY=( $(compgen -W "` + prefixAll(shorts(opts), "-") + `" -- "$cur") )
            return ;;
    esac
}

complete -o filenames -F _sl sl
`)
	return b.String()
}

// zsh emits a _sl completion function for $fpath.
//
// Every option carries its help text in brackets, which is what makes zsh list
// "the option -- what it does" the way dpkg's completion does. A short flag and
// its long name are one entry: `'(--all -a)'{--all,-a}'[desc]'` expands to two
// specs that know about each other, so zsh prints one line for the pair instead
// of two identical descriptions.
func zsh(opts []opt) string {
	_, _, _, fixed := classify(opts)
	var b strings.Builder
	b.WriteString(`#compdef sl
# zsh completion for sl -- generated by tools/completions, do not edit
#
# Install: /usr/share/zsh/vendor-completions/_sl on Debian/Ubuntu,
#          /usr/share/zsh/site-functions/_sl elsewhere (both in $fpath),
#          then run compinit (or open a new shell).

_sl_groups() {
    # the value of --rule is "RE -> GROUP"; offer GROUP once the arrow is typed
    local cur=${(Q)PREFIX}
    local -a cand
    if [[ $cur == *'-> '* || $cur == *'->' ]]; then
        local head=${cur%->*}
        local g
        for g in ` + strings.Join(groups, " ") + `; do
            cand+=( "${head}-> ${g}" )
        done
        compadd -a cand
    fi
}

_sl() {
    local -a args
    args=(
`)
	for _, o := range opts {
		b.WriteString("        " + zshSpec(o, fixed) + "\n")
	}
	b.WriteString(`        '*:file:_files'
    )
    _arguments -s -S "${args[@]}"
}

_sl "$@"
`)
	return b.String()
}

// zshSpec renders one option as an _arguments spec, description included.
//
// The whole spec has to be one shell word, and the brace form that pairs a short
// flag with its long name has to keep its braces unquoted, so the tail is
// quoted on its own and any single quote inside a description is written the
// only way zsh allows: close the quote, escape, reopen.
func zshSpec(o opt, fixed map[string][]string) string {
	tail := "[" + escZsh(o.help) + "]"
	if o.hasArg || o.optArg {
		// "=" means the value is attached (--opt=value), "+" means it may be
		// attached or given as the next word; the "-" after "=" makes it
		// optional, which is exactly --color: "-c" alone means "always".
		sep, colon := "+", ":"
		if o.optArg {
			sep, colon = "=-", "::"
		}
		tail = sep + "[" + escZsh(o.help) + "]" + colon + escZsh(o.arg) + ":" + zshAction(o, fixed)
	}
	tail = strings.ReplaceAll(tail, "'", `'\''`)
	if o.short != "" && len(o.short) == 1 {
		return fmt.Sprintf("'(--%s -%s)'{--%s,-%s}'%s'", o.long, o.short, o.long, o.short, tail)
	}
	return fmt.Sprintf("'--%s%s'", o.long, tail)
}

// zshAction is what zsh offers after the option's value: a fixed list, the group
// names, command names, files, or nothing at all (a single space).
func zshAction(o opt, fixed map[string][]string) string {
	if v, ok := fixed[o.long]; ok {
		return "(" + strings.Join(v, " ") + ")"
	}
	if o.long == "rule" {
		return "_sl_groups"
	}
	if commandValued[o.long] {
		return "_command_names -e"
	}
	if pathValued[o.long] {
		return "_files"
	}
	return " "
}

// fish emits a vendor completion file.
func fish(opts []opt) string {
	_, _, _, fixed := classify(opts)
	var b strings.Builder
	b.WriteString(`# fish completion for sl -- generated by tools/completions, do not edit
#
# Install: /usr/share/fish/vendor_completions.d/sl.fish

complete -c sl -f
`)
	for _, o := range opts {
		parts := []string{"complete -c sl", "-l " + o.long}
		if o.short != "" && len(o.short) == 1 {
			parts = append(parts, "-s "+o.short)
		}
		switch {
		case o.long == "rule":
			parts = append(parts, "-x", "-a '(sl_rule_groups)'")
		case len(fixed[o.long]) > 0:
			parts = append(parts, "-x", "-a '"+strings.Join(fixed[o.long], " ")+"'")
		case o.hasArg || o.optArg:
			parts = append(parts, "-r")
		}
		if o.help != "" {
			parts = append(parts, "-d "+fishQuote(o.help))
		}
		fmt.Fprintf(&b, "%s\n", strings.Join(parts, " "))
	}
	b.WriteString(`
# The value of --rule is "RE -> GROUP". Once the arrow is on the line only a
# group name can follow it, so the candidates are rebuilt from the arrow on:
# whatever was typed before it is kept and the group list is offered after.
function sl_rule_groups
    set -l tok (commandline -ct)
    if not string match -q '*->*' -- $tok
        return
    end
    set -l head (string replace -r -- '->.*$' '' -- $tok)
    for g in ` + strings.Join(groups, " ") + `
        printf '%s-> %s\n' "$head" "$g"
    end
end
`)
	return b.String()
}

func prefixAll(words []string, prefix string) string {
	out := make([]string, len(words))
	for i, w := range words {
		out[i] = prefix + w
	}
	return strings.Join(out, " ")
}

func shorts(opts []opt) []string {
	var out []string
	for _, o := range opts {
		if o.short != "" && len(o.short) == 1 {
			out = append(out, o.short)
		}
	}
	return out
}

func sortedKeys(m map[string][]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	for i := 1; i < len(keys); i++ {
		for j := i; j > 0 && keys[j] < keys[j-1]; j-- {
			keys[j], keys[j-1] = keys[j-1], keys[j]
		}
	}
	return keys
}

// fishQuote is the same for fish, where a backslash and a single quote are
// escaped with a backslash inside single quotes.
func fishQuote(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, "'", `\'`)
	return "'" + s + "'"
}

// escZsh keeps descriptions from breaking a zsh optspec on [ ] and :
func escZsh(s string) string {
	r := strings.NewReplacer(`\`, `\\`, "[", `\[`, "]", `\]`, ":", `\:`)
	return r.Replace(s)
}
